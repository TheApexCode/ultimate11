// Helper to create an instantiated player card with dynamic ID and level
export function instantiateCard(templateId: string, level = 1): PlayerCard {
  const t = RAW_PLAYERS_POOL.find((c) => c.templateId === templateId) || RAW_PLAYERS_POOL[0];
  const boost = (level - 1) * 2;
  return {
    ...t,
    id: `${t.templateId}-${Date.now()}-${Math.floor(Math.random() * 100000)}`,
    ovr: Math.min(99, t.ovr + boost),
    att: Math.min(99, t.att + boost),
    def: Math.min(99, t.def + boost),
    ctr: Math.min(99, t.ctr + boost),
    sta: Math.min(99, t.sta + boost),
    level,
    exp: 0,
    duplicates: 0,
  };
}

