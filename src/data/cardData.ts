// Draw a random card with rarity distribution weights
export function drawRandomCard(packTier: 'standard' | 'rare' | 'icon' = 'standard'): PlayerCard {
  let rarityWeights: Record<CardRarity, number>;

  if (packTier === 'icon') {
    rarityWeights = {
      'Cyber-Icon': 35,
      Legendary: 45,
      Epic: 20,
      Rare: 0,
      Common: 0,
    };
  } else if (packTier === 'rare') {
    rarityWeights = {
      'Cyber-Icon': 8,
      Legendary: 22,
      Epic: 45,
      Rare: 25,
      Common: 0,
    };
  } else {
    // Standard Pack
    rarityWeights = {
      'Cyber-Icon': 3,
      Legendary: 12,
      Epic: 30,
      Rare: 35,
      Common: 20,
    };
  }

  // Roll rarity
  const roll = Math.random() * 100;
  let cumulative = 0;
  let selectedRarity: CardRarity = 'Common';

  const rarities: CardRarity[] = ['Cyber-Icon', 'Legendary', 'Epic', 'Rare', 'Common'];
  for (const r of rarities) {
    cumulative += rarityWeights[r];
    if (roll <= cumulative) {
      selectedRarity = r;
      break;
    }
  }

  // Filter pool by chosen rarity
  let candidates = RAW_PLAYERS_POOL.filter((c) => c.rarity === selectedRarity);
  if (candidates.length === 0) {
    candidates = RAW_PLAYERS_POOL;
  }

  const chosenTemplate = candidates[Math.floor(Math.random() * candidates.length)];
  return instantiateCard(chosenTemplate.templateId, 1);
}

// Generate an AI squad scaled to difficulty
export function generateAISquad(difficulty: 'Amateur' | 'World Class' | 'AI Overlord'): {
  name: string;
  crest: string;
  cards: PlayerCard[];
} {
  let gks: string[];
  let defs: string[];
  let mids: string[];
  let atts: string[];
  let teamName: string;
  let level = 1;

  if (difficulty === 'AI Overlord') {
    teamName = 'Cyber Dynamos Prime';
    level = 5;
    gks = ['yashin-icon', 'buffon-icon'];
    defs = ['maldini-icon', 'vandijk-leg', 'dias-leg', 'rudiger-epic', 'theo-epic'];
    mids = ['zidane-icon', 'ronaldinho-icon', 'debruyne-leg', 'rodri-leg', 'bellingham-leg'];
    atts = ['messi-icon', 'ronaldo-icon', 'mbappe-leg', 'haaland-leg', 'vinicius-leg'];
  } else if (difficulty === 'World Class') {
    teamName = 'Apex Neon All-Stars';
    level = 3;
    gks = ['courtois-leg', 'alisson-leg'];
    defs = ['vandijk-leg', 'saliba-epic', 'rudiger-epic', 'theo-epic', 'trent-epic'];
    mids = ['debruyne-leg', 'bellingham-leg', 'valverde-epic', 'wirtz-epic', 'rice-epic'];
    atts = ['mbappe-leg', 'haaland-leg', 'salah-leg', 'kane-leg', 'saka-epic'];
  } else {
    // Amateur
    teamName = 'Neo Academy IX';
    level = 1;
    gks = ['raya-rare', 'kobel-common'];
    defs = ['gvardiol-rare', 'davies-rare', 'gabriel-rare', 'martinez-common', 'hakimi-rare'];
    mids = ['pedri-rare', 'camavinga-rare', 'macallister-common', 'odegaard-epic'];
    atts = ['martinez-rare', 'leao-rare', 'osimhen-rare', 'isak-common'];
  }

  // Pick 1 GK, 4 DEF, 3 MID, 3 ATT = 11 Cards
  const selected: string[] = [];
  selected.push(gks[Math.floor(Math.random() * gks.length)]);

  const shuffledDefs = [...defs].sort(() => 0.5 - Math.random());
  for (let i = 0; i < 4; i++) {
    selected.push(shuffledDefs[i % shuffledDefs.length]);
  }

  const shuffledMids = [...mids].sort(() => 0.5 - Math.random());
  for (let i = 0; i < 3; i++) {
    selected.push(shuffledMids[i % shuffledMids.length]);
  }

  const shuffledAtts = [...atts].sort(() => 0.5 - Math.random());
  for (let i = 0; i < 3; i++) {
    selected.push(shuffledAtts[i % shuffledAtts.length]);
  }

  return {
    name: teamName,
    crest: '🦁',
    cards: selected.map((tid) => instantiateCard(tid, level)),
  };
}
